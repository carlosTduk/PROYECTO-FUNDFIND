    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
    String correo = txtCorreo.getText();
    String pass = new String(txtPass.getPassword());

    UsuarioDonador donador = sistema.loginDonador(correo, pass);

    if (donador != null) {
        //para donador
        TableroDonador tablero = new TableroDonador(sistema, donador);
        tablero.setVisible(true);
        this.dispose(); 
        return; 
    }

    //
    Fundación fundacion = sistema.loginFundacion(correo, pass);

    if (fundacion != null) {
        //para fundación
        TableroFundacion tablero = new TableroFundacion(sistema, fundacion);
        tablero.setVisible(true);
        this.dispose();
        return;
    }

    //credenciales incorrectas
    javax.swing.JOptionPane.showMessageDialog(this, "Credenciales incorrectas.");
    }//GEN-LAST:event_btnIngresarActionPerformed

